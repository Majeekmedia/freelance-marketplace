<?php

declare(strict_types=1);

use App\Models\User;
use Illuminate\Support\Facades\Password;

/*
|--------------------------------------------------------------------------
| APP_URL correctness
|--------------------------------------------------------------------------
| Every absolute URL the application generates comes from APP_URL. The failure
| mode is quiet: pages still render, but emailed links point at the wrong host.
| Because reset links are generated by a queue worker with no request context,
| APP_URL is the only source of truth there — so it is worth asserting.
|
| This cannot assert the *production* value (that is environment-specific), but
| it can assert the value is a usable absolute URL and that generated links
| share its origin.
*/

it('has a usable absolute APP_URL', function (): void {
    $url = config('app.url');

    expect($url)->not->toBeEmpty()
        ->and(filter_var($url, FILTER_VALIDATE_URL))->not->toBeFalse()
        ->and($url)->toStartWith('http');
});

it('uses APP_URL as the fallback origin when no request host applies', function (): void {
    // In a web request Laravel prefers the request host, which is why local
    // browsing looks fine even when APP_URL is wrong. The case that breaks is
    // queue/CLI context: a reset email has no request, so APP_URL is the only
    // source of the host.
    //
    // Rather than manipulate the container (which recurses), assert the
    // configured root directly — that IS the value the queued job will use.
    $expected = rtrim((string) config('app.url'), '/');

    expect($expected)->toBe(rtrim((string) env('APP_URL'), '/'));

    // And prove the fallback produces the configured origin.
    URL::forceRootUrl($expected);
    expect(url('/reset-password/abc'))->toStartWith($expected);
});

it('builds a password reset link on the configured origin', function (): void {
    $user = User::factory()->create(['email' => 'reset-link@example.test']);
    $token = Password::createToken($user);

    $link = url(route('password.reset', ['token' => $token, 'email' => $user->email], false));

    expect($link)->toStartWith(rtrim(config('app.url'), '/'))
        ->and($link)->toContain('/reset-password/'.$token);
});
